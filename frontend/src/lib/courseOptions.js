const EMPTY_VISIBLE_COUNT = 16;
const SEARCH_VISIBLE_COUNT = 24;

const normalizeCourseOption = (value) =>
  String(value || "")
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();

const AFTER_10_OPTION_SET = new Set(AFTER_10_COURSE_OPTIONS.map(normalizeCourseOption));
const AFTER_12_OPTION_SET = new Set(AFTER_12_COURSE_OPTIONS.map(normalizeCourseOption));

const matchesQuery = (option, query) => normalizeCourseOption(option).includes(normalizeCourseOption(query));

export const detectRecommendedAcademicLevel = (courseTitle) => {
  const normalized = normalizeCourseOption(courseTitle);
  if (!normalized) {
    return null;
  }
  if (AFTER_10_OPTION_SET.has(normalized)) {
    return "10";
  }
  if (AFTER_12_OPTION_SET.has(normalized)) {
    return "12";
  }
  return null;
};

const buildSuggestionGroup = ({ label, level, options, query }) => {
  const filtered = query ? options.filter((option) => matchesQuery(option, query)) : options;
  const visibleCount = query ? SEARCH_VISIBLE_COUNT : EMPTY_VISIBLE_COUNT;

  return {
    label,
    level,
    total: filtered.length,
    options: filtered.slice(0, visibleCount)
  };
};

const resolveOptionPools = (eligibleAcademicLevels) => {
  const normalizedLevels = String(eligibleAcademicLevels || "")
    .split(",")
    .map((item) => item.trim())
    .filter(Boolean);

  const include10 = normalizedLevels.length === 0 || normalizedLevels.includes("10");
  const include12 = normalizedLevels.length === 0 || normalizedLevels.includes("12");
  const pools = [];

  if (include10) {
    pools.push({ label: "After Class 10", level: "10", options: AFTER_10_COURSE_OPTIONS });
  }

  if (include12) {
    pools.push({ label: "After Class 12", level: "12", options: AFTER_12_COURSE_OPTIONS });
  }

  return pools;
};

export const buildCourseSuggestionGroups = (eligibleAcademicLevels, query = "") => {
  return resolveOptionPools(eligibleAcademicLevels)
    .map((group) => buildSuggestionGroup({ ...group, query }))
    .filter((group) => group.total > 0);
};

export const buildAllCourseSuggestionOptions = (eligibleAcademicLevels) =>
  resolveOptionPools(eligibleAcademicLevels)
    .flatMap((group) => group.options)
    .filter((option, index, values) => values.indexOf(option) === index);
